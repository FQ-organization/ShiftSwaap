// Generates dev_seed.sql: the demo doctors, rooms and shifts the app shows in local demo mode.
// Run: node supabase/seed/gen-dev-seed.mjs > supabase/seed/dev_seed.sql
// Only ever apply the output to the DEV tenant.

const PASSWORD = 'demo1234';
const ORDER = ['F', 'A', 'B', 'D', 'I', 'M', 'J', 'N', 'R', 'T'];
const P = { F: ['Francisco', 'R2'], A: ['Ana', 'R1'], B: ['Beatriz', 'R2'], D: ['Diogo', 'R1'], I: ['Inês', 'R2'], M: ['Maria', 'R4'], J: ['João', 'R3'], N: ['André', 'R4'], R: ['Rita', 'R3'], T: ['Tiago', 'R4'] };
const JU = ['F', 'A', 'B', 'D', 'I'], SE = ['M', 'J', 'N', 'R', 'T'];
const H = 36e5;

// must match DEMO_IDS in index.html
const uid = k => '00000000-0000-4000-8000-' + String(ORDER.indexOf(k) + 1).padStart(12, '0');
const roomId = { em: '00000000-0000-4000-9000-000000000001', icu: '00000000-0000-4000-9000-000000000002' };
const email = k => P[k][0].normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/[^a-z]/g, '') + '@hospitalcentral.example';
const lit = s => "'" + String(s).replace(/'/g, "''") + "'";

// same generators as the app's local demo (makeS / icuShifts)
const makeS = () => Array.from({ length: 182 }, (_, k) => ({ start: Date.UTC(2026, 9, 1 + k, 8), m: [JU[k % 5], SE[(k + Math.floor(k / 5)) % 5]] }));
function icuShifts() {
  const mem = ['M', 'J', 'T', 'A', 'B'], sen = ['M', 'J', 'T'], cn = {}, em = makeS(), out = [];
  mem.forEach(x => cn[x] = 0);
  for (let k = 0; k < 182; k += 2) {
    const busy = new Set();
    for (let d = k - 1; d <= k + 1; d++) if (em[d]) em[d].m.forEach(x => busy.add(x));
    const free = mem.filter(x => !busy.has(x)).sort((a, b) => cn[a] - cn[b]), s1 = free.find(x => sen.includes(x)), s2 = free.find(x => x != s1);
    if (!s1 || !s2) continue;
    cn[s1]++; cn[s2]++;
    out.push({ start: Date.UTC(2026, 9, 1 + k, 8), m: [s2, s1] });
  }
  return out;
}

const out = [];
const w = s => out.push(s);
w('-- GENERATED by gen-dev-seed.mjs. Demo data for the DEV tenant only. Every demo account uses password ' + PASSWORD + '.');
w('begin;');
w('-- reset demo data so the seed can be re-run');
w(`delete from public.rooms where id in (${lit(roomId.em)}, ${lit(roomId.icu)});`);
w(`delete from auth.users where id in (${ORDER.map(k => lit(uid(k))).join(', ')});`);

w('\n-- demo accounts (the on_auth_user_created trigger creates their profiles)');
const users = ORDER.map((k, i) => ({ id: uid(k), email: email(k), name: P[k][0], year: P[k][1], avatar: i }));
w(`insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at, raw_app_meta_data, raw_user_meta_data, created_at, updated_at, confirmation_token, recovery_token, email_change_token_new, email_change)
select '00000000-0000-0000-0000-000000000000', (u->>'id')::uuid, 'authenticated', 'authenticated', u->>'email', extensions.crypt(${lit(PASSWORD)}, extensions.gen_salt('bf')), now(),
  '{"provider":"email","providers":["email"]}', jsonb_build_object('name', u->>'name', 'year', u->>'year'), now(), now(), '', '', '', ''
from jsonb_array_elements(${lit(JSON.stringify(users))}::jsonb) u;`);
w(`insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
select gen_random_uuid(), id, id::text, jsonb_build_object('sub', id::text, 'email', email, 'email_verified', true), 'email', now(), now(), now()
from auth.users where id in (${users.map(u => lit(u.id)).join(', ')});`);
w(`update public.profiles p set avatar = (u->>'avatar')::int from jsonb_array_elements(${lit(JSON.stringify(users.map(u => ({ id: u.id, avatar: u.avatar }))))}::jsonb) u where p.id = (u->>'id')::uuid;`);

const rooms = [
  { key: 'em', name: 'Emergency Medicine', icon: '🚑', bg: '#dff0ff', type: 'Emergency 24h', members: ORDER, admins: ['M'], shifts: makeS(), by: 'M', welcome: 'Welcome! Post shift changes here and colleagues who can help will be notified 👋',
    rules: [['Junior + Senior Coverage', 'require', null, null, [{ min: 1, in: ['R1', 'R2'] }, { min: 1, in: ['R3', 'R4'] }]], ['Minimum staffing', 'staff', 2, null, null], ['Minimum rest', 'rest', null, 11, null]] },
  { key: 'icu', name: 'Intensive Care', icon: '🫀', bg: '#ffe4ec', type: 'ICU 24h', members: ['M', 'J', 'T', 'A', 'B'], admins: ['J'], shifts: icuShifts(), by: 'J', welcome: 'Welcome to ICU scheduling 💙',
    rules: [['Senior supervision', 'require', null, null, [{ min: 1, in: ['R3', 'R4'] }]], ['Minimum staffing', 'staff', 2, null, null], ['Minimum rest', 'rest', null, 11, null]] }];

for (const r of rooms) {
  const rid = roomId[r.key];
  w(`\n-- room: ${r.name}`);
  w(`insert into public.rooms (id, name, icon, bg, shift_type, created_by) values (${lit(rid)}, ${lit(r.name)}, ${lit(r.icon)}, ${lit(r.bg)}, ${lit(r.type)}, ${lit(uid(r.by))});`);
  w(`insert into public.room_members (room_id, user_id, is_admin) values\n${r.members.map(k => `(${lit(rid)}, ${lit(uid(k))}, ${r.admins.includes(k)})`).join(',\n')};`);
  r.rules.forEach(([name, type, nn, h, req], i) =>
    w(`insert into public.rules (room_id, name, type, n, h, req, created_at) values (${lit(rid)}, ${lit(name)}, ${lit(type)}, ${nn ?? 'null'}, ${h ?? 'null'}, ${req ? lit(JSON.stringify(req)) + '::jsonb' : 'null'}, now() + interval '${i} seconds');`));
  w(`insert into public.messages (room_id, user_id, text, tr) values (${lit(rid)}, ${lit(uid(r.by))}, ${lit(r.welcome)}, true);`);
  // compact form: [day, [member numbers]]; member n is user ...8000-00000000000n
  const data = r.shifts.map(s => [new Date(s.start).toISOString().slice(0, 10), s.m.map(k => ORDER.indexOf(k) + 1)]);
  w(`with src as (
  select (e->>0)::date + time '08:00' as day, e->1 as m from jsonb_array_elements(${lit(JSON.stringify(data))}::jsonb) e),
ins as (
  insert into public.shifts (room_id, starts_at, ends_at, shift_type)
  select ${lit(rid)}, day at time zone 'UTC', (day at time zone 'UTC') + interval '24 hours', ${lit(r.type)} from src
  returning id, starts_at)
insert into public.shift_members (shift_id, room_id, user_id, pos)
select ins.id, ${lit(rid)}, ('00000000-0000-4000-8000-' || lpad(x.v, 12, '0'))::uuid, (x.o - 1)::smallint
from ins join src on ins.starts_at = src.day at time zone 'UTC'
cross join lateral jsonb_array_elements_text(src.m) with ordinality x(v, o);`);
}
w('\ncommit;');
